/**
 * Translate a key for the given language, with {var} interpolation and a
 * fallback to zh-Hant (then the raw key) if a string is ever missing.
 * @param {string} lang
 * @param {string} key
 * @param {Record<string,string>} [vars]
 * @returns {string}
 */
export function t(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS['zh-Hant']
  let str = dict[key] ?? STRINGS['zh-Hant'][key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, v)
    }
  }
  return str
}

